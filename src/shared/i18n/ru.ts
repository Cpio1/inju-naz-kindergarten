/** «4 года» but «5 лет»: Russian plural for the upper age bound. */
const years = (n: number) => {
  const d = n % 10;
  const dd = n % 100;
  if (d === 1 && dd !== 11) return "год";
  if (d >= 2 && d <= 4 && (dd < 12 || dd > 14)) return "года";
  return "лет";
};

